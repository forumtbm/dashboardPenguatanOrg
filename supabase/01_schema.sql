-- ---------------------------------------------------------------------
-- 0. PROFIL PENGGUNA & PERAN
-- ---------------------------------------------------------------------
-- superadmin : semua akses + kelola semua user
-- admin      : CRUD data + kelola user operator/viewer
-- operator   : CRUD data
-- viewer     : hanya melihat
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  full_name text,
  role text not null default 'viewer'
    check (role in ('superadmin','admin','operator','viewer')),
  created_at timestamptz not null default now()
);

create or replace function public.current_role_name()
returns text language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid()
$$;

create or replace function public.has_access()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid())
$$;

create or replace function public.can_edit()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.current_role_name() in ('superadmin','admin','operator'), false)
$$;

alter table public.profiles enable row level security;
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
  using (id = auth.uid() or public.current_role_name() in ('superadmin','admin'));
-- insert/update/delete profil hanya lewat server (service role key)

