-- Normalisasi nama wilayah: huruf besar, spasi tunggal, "PROV." dll diabaikan
create or replace function public.norm_wilayah(t text)
returns text language sql immutable as $$
  select nullif(regexp_replace(upper(trim(coalesce(t,''))), '\s+', ' ', 'g'), '')
$$;

-- Trigger: cocokkan provinsi_nama & kabupaten_nama ke tabel referensi
create or replace function public.tbm_resolve_wilayah()
returns trigger language plpgsql as $$
declare
  p text := public.norm_wilayah(new.provinsi_nama);
  k text := public.norm_wilayah(new.kabupaten_nama);
begin
  new.provinsi_kode := null;
  new.kabupaten_id := null;
  if p is not null then
    select kode into new.provinsi_kode from public.ref_provinsi
     where nama = p
        or nama = replace(replace(p, 'SUMATERA', 'SUMATRA'), 'PROVINSI ', '')
        or (p = 'DAERAH ISTIMEWA YOGYAKARTA' and kode = '15')
        or (p in ('JAKARTA','DAERAH KHUSUS IBUKOTA JAKARTA') and kode = '13')
        or (p in ('KEPULAUAN BANGKA BELITUNG') and kode = '09')
     limit 1;
  end if;
  if k is not null then
    select id into new.kabupaten_id from public.ref_kabupaten
     where (new.provinsi_kode is null or provinsi_kode = new.provinsi_kode)
       and (nama = k or nama = 'KABUPATEN ' || k or nama = 'KOTA ' || k
            or nama = 'KOTA ADMINISTRASI ' || k
            or nama = replace(k, 'KAB. ', 'KABUPATEN ')
            or nama = replace(k, 'KAB ', 'KABUPATEN '))
     order by (nama = k) desc, (nama like 'KABUPATEN %') desc
     limit 1;
    if new.provinsi_kode is null and new.kabupaten_id is not null then
      select provinsi_kode into new.provinsi_kode from public.ref_kabupaten where id = new.kabupaten_id;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists tbm_resolve_wilayah_trg on public.tbm;
create trigger tbm_resolve_wilayah_trg before insert or update on public.tbm
  for each row execute function public.tbm_resolve_wilayah();

-- updated_at otomatis
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists pw_touch on public.pengurus_wilayah;
create trigger pw_touch before update on public.pengurus_wilayah
  for each row execute function public.touch_updated_at();
drop trigger if exists pd_touch on public.pengurus_daerah;
create trigger pd_touch before update on public.pengurus_daerah
  for each row execute function public.touch_updated_at();
drop trigger if exists tbm_touch on public.tbm;
create trigger tbm_touch before update on public.tbm
  for each row execute function public.touch_updated_at();

-- Sinkronkan sequence id TBM setelah impor CSV yang membawa kolom id
create or replace function public.sync_tbm_id_seq()
returns void language sql security definer set search_path = public as $$
  select setval(pg_get_serial_sequence('public.tbm','id'),
                greatest(coalesce((select max(id) from public.tbm), 0), 1),
                (select count(*) > 0 from public.tbm));
$$;
revoke all on function public.sync_tbm_id_seq() from public, anon;
grant execute on function public.sync_tbm_id_seq() to authenticated;

-- ---------------------------------------------------------------------
-- 5. VIEW UNTUK DASHBOARD
--    "Terbentuk" = status AKTIF atau TIDAK_AKTIF.
--    PRESIDIUM (PW) / PEMBENTUKAN (PD) dihitung "belum terbentuk".
-- ---------------------------------------------------------------------
create or replace view public.v_daerah with (security_invoker = true) as
select
  k.id as kabupaten_id, k.nama as kabupaten_nama, k.kode as kabupaten_kode,
  p.kode as provinsi_kode, p.nama as provinsi_nama,
  pw.status as status_pw, pd.status as status_pd, pd.id as pd_id,
  (select count(*) from public.tbm t where t.kabupaten_id = k.id)::int as jumlah_tbm
from public.ref_kabupaten k
join public.ref_provinsi p on p.kode = k.provinsi_kode
left join public.pengurus_wilayah pw on pw.provinsi_kode = p.kode
left join public.pengurus_daerah pd on pd.kabupaten_id = k.id;

create or replace view public.v_provinsi with (security_invoker = true) as
select
  p.kode as provinsi_kode, p.nama as provinsi_nama,
  pw.id as pw_id, pw.status as status_pw,
  (select count(*) from public.ref_kabupaten k where k.provinsi_kode = p.kode)::int as jumlah_kabupaten,
  (select count(*) from public.pengurus_daerah d join public.ref_kabupaten k on k.id = d.kabupaten_id
     where k.provinsi_kode = p.kode and d.status in ('AKTIF','TIDAK_AKTIF'))::int as jumlah_pd,
  (select count(*) from public.pengurus_daerah d join public.ref_kabupaten k on k.id = d.kabupaten_id
     where k.provinsi_kode = p.kode and d.status = 'AKTIF')::int as pd_aktif,
  (select count(*) from public.pengurus_daerah d join public.ref_kabupaten k on k.id = d.kabupaten_id
     where k.provinsi_kode = p.kode and d.status = 'TIDAK_AKTIF')::int as pd_tidak_aktif,
  (select count(*) from public.pengurus_daerah d join public.ref_kabupaten k on k.id = d.kabupaten_id
     where k.provinsi_kode = p.kode and d.status = 'PEMBENTUKAN')::int as pd_pembentukan,
  (select count(*) from public.tbm t where t.provinsi_kode = p.kode)::int as jumlah_tbm
from public.ref_provinsi p
left join public.pengurus_wilayah pw on pw.provinsi_kode = p.kode;

create or replace view public.v_tbm_status with (security_invoker = true) as
select coalesce(status, '(kosong)') as status, count(*)::int as jumlah
from public.tbm group by 1 order by 1;

-- ---------------------------------------------------------------------
-- 6. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['ref_provinsi','ref_kabupaten','pengurus_wilayah','pengurus_daerah','tbm'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.has_access())', t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_write', t);
    execute format('create policy %I on public.%I for all to authenticated using (public.can_edit()) with check (public.can_edit())', t || '_write', t);
  end loop;
end $$;

revoke all on all tables in schema public from anon;
