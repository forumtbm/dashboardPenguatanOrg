create table if not exists public.tbm_portofolio (
  id bigint generated by default as identity primary key,
  tbm_id bigint not null references public.tbm(id) on delete cascade,
  tanggal date not null default current_date,
  judul text,
  isi text not null,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists tbm_portofolio_tbm_idx on public.tbm_portofolio(tbm_id, tanggal desc);

drop trigger if exists tbm_portofolio_touch on public.tbm_portofolio;
create trigger tbm_portofolio_touch before update on public.tbm_portofolio
  for each row execute function public.touch_updated_at();

alter table public.tbm_portofolio enable row level security;
drop policy if exists tbm_portofolio_read on public.tbm_portofolio;
create policy tbm_portofolio_read on public.tbm_portofolio for select to authenticated using (public.has_access());
drop policy if exists tbm_portofolio_write on public.tbm_portofolio;
create policy tbm_portofolio_write on public.tbm_portofolio for all to authenticated
  using (public.can_edit()) with check (public.can_edit());

-- Elemen jsonb array -> baris teks (aman untuk null / bukan array)
create or replace function public.jarr(j jsonb)
returns setof text language sql immutable as $$
  select jsonb_array_elements_text(case when jsonb_typeof(j) = 'array' then j else '[]'::jsonb end)
$$;

-- ---------------------------------------------------------------------
-- Opsi dropdown filter (diambil dari isian data TBM yang ada)
-- ---------------------------------------------------------------------
create or replace function public.tbm_opsi_filter()
returns table(kolom text, nilai text, jumlah int)
language sql stable security invoker set search_path = public as $$
  select * from (
    select 'badan_hukum'::text, kelembagaan_bentuk, count(*)::int from tbm
      where nullif(trim(kelembagaan_bentuk), '') is not null group by 2
    union all
    select 'literasi', v, count(distinct t.id)::int from tbm t, jarr(t.program_layanan_literasi_dasar) v group by 2
    union all
    select 'kegiatan', v, count(distinct t.id)::int from tbm t, jarr(t.program_kegiatan_kerap) v group by 2
    union all
    select 'jml_buku', program_jml_buku, count(*)::int from tbm
      where nullif(trim(program_jml_buku), '') is not null group by 2
    union all
    select 'sumber_dana', v, count(distinct t.id)::int from tbm t, jarr(t.program_sumber_dana) v group by 2
    union all
    select 'kap_minat', kap_minat_pengembangan, count(*)::int from tbm
      where nullif(trim(kap_minat_pengembangan), '') is not null group by 2
    union all
    select 'kap_topik', v, count(distinct t.id)::int from tbm t,
      lateral (select jarr(t.kap_topik_literasi) union select jarr(t.kap_topik_keorganisasian)
               union select jarr(t.kap_topik_kecakapan_diri) union select jarr(t.kap_topik_kecakapan_hidup)) x(v)
      group by 2
  ) s(kolom, nilai, jumlah)
  order by kolom, jumlah desc, nilai
$$;

-- ---------------------------------------------------------------------
-- Pencarian + filter TBM & portofolio
--   p_keyword : semua kata harus ditemukan di Nama TBM / No. anggota /
--               Lokasi (provinsi, kab/kota, kecamatan, desa) / isi portofolio
-- ---------------------------------------------------------------------
drop function if exists public.cari_portofolio(text,text,text,text,text,text,text,text,int,int);
create or replace function public.cari_portofolio(
  p_keyword text default null,
  p_badan_hukum text default null,
  p_literasi text default null,
  p_kegiatan text default null,
  p_jml_buku text default null,
  p_sumber_dana text default null,
  p_kap_minat text default null,
  p_kap_topik text default null,
  p_limit int default 20,
  p_offset int default 0
)
returns table(
  tbm_id bigint, nama_tbm text, nomor_anggota_tbm text, provinsi text, kabupaten text,
  status text, kelembagaan_bentuk text, program_jml_buku text,
  jumlah_portofolio int, portofolio_terakhir date,
  cuplikan_judul text, cuplikan text, cocok_di text[], total bigint
)
language sql stable security invoker set search_path = public as $$
  with kw as (
    select coalesce(array_remove(regexp_split_to_array(lower(trim(coalesce(p_keyword, ''))), '\s+'), ''), '{}') as words
  ),
  base as (
    select t.id, t.nama_tbm, t.nomor_anggota_tbm, t.status, t.kelembagaan_bentuk, t.program_jml_buku,
      t.program_layanan_literasi_dasar, t.program_kegiatan_kerap, t.program_sumber_dana,
      t.kap_minat_pengembangan, t.kap_topik_literasi, t.kap_topik_keorganisasian,
      t.kap_topik_kecakapan_diri, t.kap_topik_kecakapan_hidup,
      coalesce(p.nama, t.provinsi_nama) as prov,
      coalesce(k.nama, t.kabupaten_nama) as kab,
      lower(concat_ws(' ', t.nama_tbm, t.nomor_anggota_tbm)) as txt_nama,
      lower(concat_ws(' ', t.provinsi_nama, t.kabupaten_nama, p.nama, k.nama, t.alamat_kecamatan, t.alamat_desa)) as txt_lokasi,
      coalesce((select lower(string_agg(concat_ws(' ', pf.judul, pf.isi), ' ')) from tbm_portofolio pf where pf.tbm_id = t.id), '') as txt_porto
    from tbm t
    left join ref_kabupaten k on k.id = t.kabupaten_id
    left join ref_provinsi p on p.kode = t.provinsi_kode
  ),
  filtered as (
    select b.*,
      (select count(*) from unnest(kw.words) w where position(w in b.txt_nama) > 0) * 3
      + (select count(*) from unnest(kw.words) w where position(w in b.txt_lokasi) > 0) * 2
      + (select count(*) from unnest(kw.words) w where position(w in b.txt_porto) > 0) as skor
    from base b, kw
    where (p_badan_hukum is null or b.kelembagaan_bentuk = p_badan_hukum)
      and (p_literasi is null or b.program_layanan_literasi_dasar ? p_literasi)
      and (p_kegiatan is null or b.program_kegiatan_kerap ? p_kegiatan)
      and (p_jml_buku is null or b.program_jml_buku = p_jml_buku)
      and (p_sumber_dana is null or b.program_sumber_dana ? p_sumber_dana)
      and (p_kap_minat is null or b.kap_minat_pengembangan = p_kap_minat)
      and (p_kap_topik is null or b.kap_topik_literasi ? p_kap_topik or b.kap_topik_keorganisasian ? p_kap_topik
           or b.kap_topik_kecakapan_diri ? p_kap_topik or b.kap_topik_kecakapan_hidup ? p_kap_topik)
      and not exists (
        select 1 from unnest(kw.words) w
        where position(w in concat_ws(' ', b.txt_nama, b.txt_lokasi, b.txt_porto)) = 0
      )
  )
  select f.id, f.nama_tbm, f.nomor_anggota_tbm, f.prov, f.kab, f.status, f.kelembagaan_bentuk, f.program_jml_buku,
    (select count(*) from tbm_portofolio pf where pf.tbm_id = f.id)::int,
    (select max(pf.tanggal) from tbm_portofolio pf where pf.tbm_id = f.id),
    c.judul, c.isi,
    case when cardinality(kw.words) = 0 then '{}'::text[] else array_remove(array[
      case when exists (select 1 from unnest(kw.words) w where position(w in f.txt_nama) > 0) then 'Nama TBM' end,
      case when exists (select 1 from unnest(kw.words) w where position(w in f.txt_lokasi) > 0) then 'Lokasi' end,
      case when exists (select 1 from unnest(kw.words) w where position(w in f.txt_porto) > 0) then 'Portofolio' end
    ], null) end,
    count(*) over ()
  from filtered f
  cross join kw
  left join lateral (
    select pf.judul, pf.isi from tbm_portofolio pf
    where pf.tbm_id = f.id
    order by exists (select 1 from unnest(kw.words) w
                     where position(w in lower(concat_ws(' ', pf.judul, pf.isi))) > 0) desc,
             pf.tanggal desc, pf.id desc
    limit 1
  ) c on true
  order by f.skor desc, f.nama_tbm nulls last, f.id
  limit greatest(1, least(p_limit, 200)) offset greatest(0, p_offset)
$$;

grant execute on function public.tbm_opsi_filter() to authenticated;
grant execute on function public.cari_portofolio(text,text,text,text,text,text,text,text,int,int) to authenticated;
